#!/usr/bin/env bash
# Write deploy/cells/<cell>.yaml from `tofu output` so malgaryd knows the cell's hosts and
# gateway pairs. Usage: infra/tools/cell-inventory.sh pilot
set -euo pipefail
env=${1:?usage: cell-inventory.sh <env>}
root=$(cd "$(dirname "$0")/../.." && pwd)
dir="$root/infra/envs/$env"
cell=$(awk -F'"' '/^cell /{print $2}' "$dir/terraform.tfvars")
region=$(awk -F'"' '/^region /{print $2}' "$dir/terraform.tfvars")
ctl_size=$(awk -F'"' '/^control_host_size /{print $2}' "$dir/terraform.tfvars")
json=$(tofu -chdir="$dir" output -json)
out="$root/deploy/cells/$cell.yaml"
{
  echo "# Generated by infra/tools/cell-inventory.sh $env. Do not edit by hand."
  echo "code: $cell"
  echo "region: $region"
  echo "maxUsers: 5000"
  echo "hosts:"
  echo "$json" | jq -r --arg size "$ctl_size" '.control_hosts.value[] | "  - {name: \(.fqdn | split(".")[0:2] | join(".")), role: control, size: \($size), maxUsers: 2500}"'
  echo "$json" | jq -r '.egress_ips.value | keys[] as $p | "  - {name: \($p)a.'"$cell"', role: gateway, size: gateway}\n  - {name: \($p)b.'"$cell"', role: gateway, size: gateway}"'
  echo "gatewayPairs:"
  echo "$json" | jq -r '.egress_ips.value | to_entries[] | "  - {name: \(.key), egressIp: \(.value), primary: \(.key)a.'"$cell"', standby: \(.key)b.'"$cell"'}"'
} > "$out"
echo "wrote $out"
